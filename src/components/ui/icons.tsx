/**
 * The console's icon set — hand-rolled 16px stroke glyphs rather than an icon
 * dependency. The sidebar needs eight of them and the toolbar three; a package
 * would ship a few hundred KB of tree-shaken-but-still-parsed JSX for that.
 *
 * All of them inherit `currentColor` and size from the `size` prop, so a nav
 * row tints its icon by setting text colour like any other glyph.
 */
type IconProps = { size?: number; className?: string };

function Svg({
  size = 16,
  className,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden
      focusable="false"
    >
      {children}
    </svg>
  );
}

