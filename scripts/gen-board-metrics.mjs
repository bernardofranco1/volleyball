/**
 * Generate src/lib/board-text-metrics.ts from the Ancorli TTF.
 *
 * The VIS boards show a 3-letter IOC code, which always fits; the table exists
 * for the FALLBACK, when VIS sends no code and the board must place a full
 * federation name inside a fixed box. That fit has to happen without measuring
 * in the browser — the boards are server-rendered onto venue TVs, and a JS fit
 * pass would paint one size and then jump — so the font's own advance widths
 * are baked in and the fit is pure arithmetic, identical on server and client.
 *
 * Kern pairs are deliberately NOT emitted: on real federation names Ancorli's
 * kerning moves the total by under 1%, which the safety margin in
 * board-text-fit.ts already covers, and the pair table is 20x the size.
 *
 * Re-run after any font change:  node scripts/gen-board-metrics.mjs
 */
import fk from "fontkit";
import { writeFileSync } from "node:fs";

const fontkit = fk.default ?? fk;
const font = fontkit.openSync("src/fonts/Ancorli.ttf");

// Every character a FIVB federation name can carry once uppercased, plus the
// digits and punctuation the other board strings use.
const CHARS = [
  " ", "!", "&", "'", "(", ")", ",", "-", ".", "/", ":",
  ...Array.from({ length: 10 }, (_, i) => String(i)),
  ...Array.from({ length: 26 }, (_, i) => String.fromCharCode(65 + i)),
  ..."ÀÁÂÃÄÅÆÇÈÉÊËÌÍÎÏÑÒÓÔÕÖØÙÚÛÜÝŞİĞ",
];

const advance = {};
let maxAdv = 0;
for (const ch of CHARS) {
  const cp = ch.codePointAt(0);
  if (!font.hasGlyphForCodePoint(cp)) continue;
  const w = font.layout(ch).advanceWidth;
  advance[ch] = w;
  if (w > maxAdv) maxAdv = w;
}

// Encode Sans Expanded Bold — the AVC broadcast package's label face (spec/47).
// Only Bold, and only because two TV graphics put a VARIABLE-length string in a
// fixed box: a substituted player's name, and "VIDEO CHALLENGE BY {TEAM}". The
// other weights set fixed strings at fixed sizes and need no table.
const encodeBold = fontkit.openSync("src/fonts/EncodeSansExpanded-Bold.ttf");
const encAdvance = {};
let encMax = 0;
for (const ch of CHARS) {
  const cp = ch.codePointAt(0);
  if (!encodeBold.hasGlyphForCodePoint(cp)) continue;
  const w = encodeBold.layout(ch).advanceWidth;
  encAdvance[ch] = w;
  if (w > encMax) encMax = w;
}

const out = `// GENERATED by scripts/gen-board-metrics.mjs — do not edit by hand.
//
// Advance widths in font units, so a board can fit text to a box
// arithmetically on the server. See src/lib/board-text-fit.ts for the fit, and
// the generator for why kern pairs are omitted.

export interface BoardFontMetrics {
  unitsPerEm: number;
  /** Cap height in font units — the boards size text by CAP, not by em. */
  capHeight: number;
  /** Used for any character missing from the table: the widest glyph, so an
   *  unknown name errs towards shrinking rather than overflowing. */
  fallbackAdvance: number;
  advance: Record<string, number>;
}

export const ANCORLI_METRICS: BoardFontMetrics = ${JSON.stringify(
  { unitsPerEm: font.unitsPerEm, capHeight: font.capHeight, fallbackAdvance: maxAdv, advance },
  null,
  2,
)};

/** Encode Sans Expanded Bold — the TV package's label face (spec/47). */
export const ENCODE_SANS_BOLD_METRICS: BoardFontMetrics = ${JSON.stringify(
  {
    unitsPerEm: encodeBold.unitsPerEm,
    capHeight: encodeBold.capHeight,
    fallbackAdvance: encMax,
    advance: encAdvance,
  },
  null,
  2,
)};
`;

writeFileSync("src/lib/board-text-metrics.ts", out);
console.log(
  `wrote src/lib/board-text-metrics.ts — ${Object.keys(advance).length} glyphs, upem ${font.unitsPerEm}, cap ${font.capHeight}`,
);

// ── Flag aspect ratios ────────────────────────────────────────────────────
// The boards size a flag on the server, before the image loads, so the natural
// ratio of every asset is baked in from its PNG header. These are the official
// ratios, and they are NOT uniform: 3:2 for most, 2:1 for six, 10:7 Brazil,
// 28:11 Qatar, 19:10 USA.
import { readdirSync, readFileSync } from "node:fs";

const ratios = {};
for (const f of readdirSync("public/flags").sort()) {
  if (!f.endsWith(".png")) continue;
  const head = readFileSync(`public/flags/${f}`).subarray(16, 24);
  const w = head.readUInt32BE(0);
  const h = head.readUInt32BE(4);
  ratios[f.slice(0, 3)] = Number((w / h).toFixed(4));
}

// The AVC broadcast package's own flag assets (spec/47). Which codes EXIST has
// to be known without a request: the TV overlay draws its flag in SVG, where a
// missing file is a 404 and a hole rather than something an onError handler can
// quietly swap out, and the overlay must fall back to public/flags for any
// federation this package does not cover.
const tvFlags = [];
for (const f of readdirSync("public/tv-flags").sort()) {
  if (f.endsWith(".webp")) tvFlags.push(f.slice(0, -5));
}

writeFileSync(
  "src/lib/board-flag-ratios.ts",
  `// GENERATED by scripts/gen-board-metrics.mjs — do not edit by hand.
//
// Natural width/height of each flag asset, read from its PNG header, so a board
// can size a flag server-side without waiting for the image. Regenerate after
// adding or replacing anything in public/flags.

export const FLAG_RATIO: Record<string, number> = ${JSON.stringify(ratios, null, 2)};

/** 3:2 — what most federations use, and a safe guess for an asset we lack. */
export const DEFAULT_FLAG_RATIO = 1.5;

/** Federations the AVC TV package supplies a flag for (public/tv-flags). */
export const TV_FLAG_CODES: ReadonlySet<string> = new Set(${JSON.stringify(tvFlags)});
`,
);
console.log(
  `wrote src/lib/board-flag-ratios.ts — ${Object.keys(ratios).length} flags, ` +
    `${tvFlags.length} tv flags`,
);
